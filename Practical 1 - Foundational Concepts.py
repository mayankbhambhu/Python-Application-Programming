# Q3 Display Integer, Float, String, Boolean
integer_value = 7
float_value = 7.7
string_value = "Seven"
boolean_value = True

print("Integer:", integer_value)
# Output: Integer: 7

print("Float:", float_value)
# Output: Float: 7.7

print("String:", string_value)
# Output: String: Seven

print("Boolean:", boolean_value)
# Output: Boolean: True

# Q4 Type Conversions
# Float to Integer
float_value = 10.5
integer_value = int(float_value)
print("Float to Integer:", integer_value)
# Output: Float to Integer: 10

# String to Integer
string_value = "25"
integer_value = int(string_value)
print("String to Integer:", integer_value)
# Output: String to Integer: 25

# Boolean to Integer
boolean_value = True
integer_value = int(boolean_value)
print("Boolean to Integer:", integer_value)
# Output: Boolean to Integer: 1

