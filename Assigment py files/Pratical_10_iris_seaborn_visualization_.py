import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

sns.set_theme(style="whitegrid", palette="Set2", context="notebook")

# Load the Iris dataset
iris = sns.load_dataset("iris")

print(f"Dataset Shape: {iris.shape[0]} rows, {iris.shape[1]} columns\n")
print("Class Distribution:\n", iris["species"].value_counts(), "\n")
display(iris.head())
display(iris.describe().round(2))

fig, axes = plt.subplots(1, 2, figsize=(15, 6))

# Subplot 1: Petal Length vs. Petal Width
sns.scatterplot(
    data=iris,
    x="petal_length",
    y="petal_width",
    hue="species",
    style="species",
    s=85,
    alpha=0.85,
    ax=axes[0]
)
axes[0].set_title("Petal Length vs. Petal Width by Species", fontsize=13, fontweight="bold")
axes[0].set_xlabel("Petal Length (cm)", fontsize=11)
axes[0].set_ylabel("Petal Width (cm)", fontsize=11)

# Subplot 2: Sepal Length vs. Sepal Width
sns.scatterplot(
    data=iris,
    x="sepal_length",
    y="sepal_width",
    hue="species",
    style="species",
    s=85,
    alpha=0.85,
    ax=axes[1]
)
axes[1].set_title("Sepal Length vs. Sepal Width by Species", fontsize=13, fontweight="bold")
axes[1].set_xlabel("Sepal Length (cm)", fontsize=11)
axes[1].set_ylabel("Sepal Width (cm)", fontsize=11)

plt.tight_layout()
plt.show()

features = ["sepal_length", "sepal_width", "petal_length", "petal_width"]
fig, axes = plt.subplots(2, 2, figsize=(15, 10))

for ax, feature in zip(axes.flat, features):
    sns.kdeplot(
        data=iris,
        x=feature,
        hue="species",
        fill=True,
        common_norm=False,
        alpha=0.45,
        linewidth=2,
        ax=ax
    )
    ax.set_title(f"Kernel Density Estimate: {feature.replace('_', ' ').title()}", fontsize=13, fontweight="bold")
    ax.set_xlabel(f"{feature.replace('_', ' ').title()} (cm)", fontsize=11)
    ax.set_ylabel("Density", fontsize=11)

plt.tight_layout()
plt.show()

fig, axes = plt.subplots(2, 2, figsize=(15, 10))

for ax, feature in zip(axes.flat, features):
    sns.violinplot(
        data=iris,
        x="species",
        y=feature,
        hue="species",
        palette="Set2",
        inner="box",
        legend=False,
        ax=ax
    )
    ax.set_title(f"Violin Plot of {feature.replace('_', ' ').title()} by Species", fontsize=13, fontweight="bold")
    ax.set_xlabel("Species", fontsize=11)
    ax.set_ylabel(f"{feature.replace('_', ' ').title()} (cm)", fontsize=11)

plt.tight_layout()
plt.show()

# Compute Pearson correlation matrix across numeric features
corr_matrix = iris.corr(numeric_only=True)

plt.figure(figsize=(8, 6))
sns.heatmap(
    corr_matrix,
    annot=True,
    fmt=".2f",
    cmap="coolwarm",
    vmin=-1,
    vmax=1,
    center=0,
    square=True,
    linewidths=1.2,
    cbar_kws={"label": "Pearson Correlation Coefficient (r)"}
)
plt.title("Feature Correlation Heatmap — Iris Dataset", fontsize=14, fontweight="bold", pad=14)
plt.tight_layout()
plt.show()

# Joint Plot 1: Species-grouped Scatter + Marginal KDEs
g1 = sns.jointplot(
    data=iris,
    x="petal_length",
    y="petal_width",
    hue="species",
    height=7,
    s=75,
    alpha=0.85
)
g1.fig.suptitle("Joint Plot: Petal Length vs. Petal Width (Grouped by Species)", y=1.02, fontsize=13, fontweight="bold")
g1.set_axis_labels("Petal Length (cm)", "Petal Width (cm)", fontsize=11)
plt.show()

# Joint Plot 2: Linear Regression + Marginal Histogram/KDE
g2 = sns.jointplot(
    data=iris,
    x="sepal_length",
    y="petal_length",
    kind="reg",
    color="#2b5c8f",
    height=7,
    scatter_kws={"alpha": 0.7, "s": 60}
)
g2.fig.suptitle("Joint Plot with Regression Fit: Sepal Length vs. Petal Length", y=1.02, fontsize=13, fontweight="bold")
g2.set_axis_labels("Sepal Length (cm)", "Petal Length (cm)", fontsize=11)
plt.show()

pair_grid = sns.pairplot(
    data=iris,
    hue="species",
    diag_kind="kde",
    palette="Set2",
    plot_kws={"alpha": 0.8, "s": 55},
    diag_kws={"fill": True, "alpha": 0.45}
)
pair_grid.fig.suptitle("Pair Plot of All Iris Features Colored by Species", y=1.02, fontsize=15, fontweight="bold")
plt.show()