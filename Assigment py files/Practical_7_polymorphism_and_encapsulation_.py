class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y

    def __repr__(self):
        return f"Point({self.x}, {self.y})"

p1 = Point(2, 3)
print(p1)

class Animal:
    def __init__(self, name):
        self.name = name

    def speak(self):
        print(self.name)

class Dog(Animal):
    pass  # Inherits __init__ and speak directly from Animal

d1 = Dog("Rex")
d1.speak()

class Cat:
    def sound(self):
        print("Meow")

class Fox:
    def sound(self):
        print("Wa-pa-pa-pa-pa-pow!")

c1 = Cat()
f1 = Fox()

c1.sound()
f1.sound()

class ScoreBoard:
    def __init__(self, score):
        self.__score = score  # The double underscore makes the attribute private

    def get_score(self):
        return self.__score

s1 = ScoreBoard(0)
print(s1.get_score())